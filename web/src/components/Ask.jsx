import React, { useState } from 'react'

const EXAMPLES = [
  'Which experiments tell us how fabrics burn in low airflow, and what did they find?',
  'Can CO2 or helium extinguish fuel droplet flames at Moon-base oxygen levels?',
  'What do we know about smoke particle sizes for designing spacecraft smoke detectors?',
  'Is there any combustion data at elevated oxygen and reduced pressure?',
]

function Cited({ text }) {
  const parts = String(text || '').split(/(\[PSI-\d+(?:,\s*PSI-\d+)*\])/g)
  return parts.map((p, i) => /^\[PSI-/.test(p)
    ? <a key={i} className="cite" href={`https://psi.nasa.gov/physci/repo/data/investigations/${p.match(/PSI-\d+/)[0]}`} target="_blank" rel="noreferrer">{p}</a>
    : <span key={i}>{p}</span>)
}

export default function Ask({ hab }) {
  const [q, setQ] = useState('')
  const [busy, setBusy] = useState(false)
  const [res, setRes] = useState(null)
  const [err, setErr] = useState(null)

  async function ask(question) {
    const text = (question ?? q).trim(); if (!text) return
    setQ(text); setBusy(true); setErr(null); setRes(null)
    try {
      const r = await fetch('/api/ask', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ question: text, habitat: hab }) })
      const j = await r.json()
      if (!r.ok) throw new Error(j.error || r.status)
      setRes(j)
    } catch (e) { setErr(String(e.message || e)) } finally { setBusy(false) }
  }

  const confClass = { high: 'good', medium: 'warn', low: 'warn', 'no-data': 'alert' }
  return (
    <div className="grid-main">
      <div className="panel">
        <h2>Ask the Flame</h2>
        <div className="small muted" style={{ marginBottom: 8 }}>Answers come only from NASA PSI investigations EMBER harvested, with citations you can open. Context: <b>{hab.name}</b> ({hab.o2}% O₂, {hab.psi} psi, {hab.g.toFixed(2)} g).</div>
        <form onSubmit={e => { e.preventDefault(); ask() }} style={{ display: 'flex', gap: 8 }}>
          <textarea rows="2" style={{ flex: 1, resize: 'vertical' }} value={q} onChange={e => setQ(e.target.value)} placeholder="e.g. How does airflow change whether a fabric keeps burning in microgravity?"
            onKeyDown={e => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); ask() } }} />
          <button className="btn primary" disabled={busy}>{busy ? 'Thinking…' : 'Ask'}</button>
        </form>
        <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap', marginTop: 8 }}>
          {EXAMPLES.map(x => <button key={x} className="chip small" onClick={() => ask(x)} disabled={busy}>{x}</button>)}
        </div>

        {err && <p className="alert small" style={{ marginTop: 12 }}>{err}</p>}
        {res && <div style={{ marginTop: 14, display: 'flex', flexDirection: 'column', gap: 12 }}>
          <div>
            <div className="tag">Answer · confidence <b className={confClass[res.confidence]}>{res.confidence}</b></div>
            <div className="answer" style={{ marginTop: 6 }}><Cited text={res.answer} /></div>
          </div>
          <div>
            <div className="tag alert">Red-team · worst credible case</div>
            <div className="answer red" style={{ marginTop: 6 }}>
              <Cited text={res.redTeam?.worstCase} />
              {res.redTeam?.gaps?.length > 0 && <><br /><br /><b>Data gaps</b>{res.redTeam.gaps.map((g, i) => <div key={i}>• <Cited text={g} /></div>)}</>}
              {res.redTeam?.doNotAssume && <><br /><b>Do not assume:</b> <Cited text={res.redTeam.doNotAssume} /></>}
            </div>
          </div>
          {res.unverifiedCitations?.length > 0 && <div className="small warn">Removed citations not found in the retrieved sources: {res.unverifiedCitations.join(', ')}</div>}
          <div className="dim small">Generated by Google Gemini ({res.model}) from PSI sources below · SI-generated text: verify before use.</div>
        </div>}
      </div>

      <div className="panel">
        <h2>Sources used</h2>
        {!res && <div className="small muted">The retrieved PSI investigations will appear here, ranked by relevance to your question.</div>}
        {res?.sources?.map(s => (
          <div key={s.id} className="row" style={{ marginBottom: 6, cursor: 'default' }}>
            <div className="t"><b>{s.acronym || s.id}</b><span className={res.citations.includes(s.id) ? 'good small' : 'dim small'}>{res.citations.includes(s.id) ? 'cited' : 'retrieved'}</span></div>
            <div className="small muted">{s.id} · {s.title}</div>
            <div className="small"><a href={`https://psi.nasa.gov/physci/repo/data/investigations/${s.id}`} target="_blank" rel="noreferrer">PSI page ↗</a>{s.doi && <> · <a href={'https://doi.org/' + s.doi} target="_blank" rel="noreferrer">DOI</a></>}</div>
          </div>
        ))}
        {res?.facts && <><h3>Computed facts given to the model</h3><div className="prose">{res.facts}</div></>}
      </div>
    </div>
  )
}
